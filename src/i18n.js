const LANGS = ["az", "ru", "en"];

function detectLang() {
  try {
    const saved = localStorage.getItem("ec.lang");
    if (LANGS.includes(saved)) return saved;
  } catch { /* */ }
  const nav = (navigator.language || "az").slice(0, 2).toLowerCase();
  return LANGS.includes(nav) ? nav : "en";
}

let currentLang = detectLang();

function t(key, vars = {}) {
  const s = I18N[currentLang]?.[key] ?? I18N.az[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`));
}

function applyI18n(root = document) {
  document.documentElement.lang = currentLang;
  root.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll("[data-i18n-html]").forEach((el) => { el.innerHTML = t(el.dataset.i18nHtml); });
  root.querySelectorAll("[data-i18n-title]").forEach((el) => { el.title = t(el.dataset.i18nTitle); });
  root.querySelectorAll("[data-i18n-placeholder]").forEach((el) => { el.placeholder = t(el.dataset.i18nPlaceholder); });
}

function setLang(lang) {
  if (!LANGS.includes(lang)) return;
  currentLang = lang;
  try { localStorage.setItem("ec.lang", lang); } catch { /* */ }
  applyI18n();
  window.__TAURI__?.core.invoke("set_language", { lang }).catch(() => {});
}

// Digər pəncərədə dil dəyişəndə bu pəncərə də yenilənsin
window.addEventListener("storage", (ev) => {
  if (ev.key === "ec.lang" && LANGS.includes(ev.newValue) && ev.newValue !== currentLang) {
    currentLang = ev.newValue;
    applyI18n();
    window.dispatchEvent(new Event("ec-lang-changed"));
  }
});
